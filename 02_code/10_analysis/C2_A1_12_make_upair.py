"""C2_A1_12_make_upair.py -- generate the unordered-pair copies of the stacked-test producers.

Usage (cwd = the analysis code folder):  python3 C2_A1_12_make_upair.py [--check]

Writes, from source files in this folder:
  C2_A2_7c_narrowA.do  A2_7b.do with the outcome set to v_unesco_a (Narrow-A, 22 HS2007 codes) only;
                       item and file tags A2.7b/A2_7b -> A2.7c/A2_7c. Directed-pair clusters, core outputs.
  UP_<stem>.do         for each stem in UP_STEMS: the source with (a) every cluster(pair_id) and
                       vce(cluster pair_id) changed to unordered_pair_id, (b) A1_stack given cl(unordered_pair_id),
                       (c) all outputs sent to the sandbox ${OUTROOT}/${VINTAGE}_upair, (d) the two inputs read
                       through ${OUT} (A2_work.dta, positive_controls.csv) read from the core folder.
Nothing else changes; every substitution count is asserted. --check regenerates in memory and exits 1 if a
file on disk differs (provenance check for the package). Coefficients do not depend on the cluster variable;
C2_A1_12_upair_table.py asserts for every posted row that N, drop counts and the estimate (Wald rows: df) are identical
under the two clusterings.
"""
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
UP_STEMS = ["A2_5", "A2_6", "A2_7", "A2_7b", "C2_A2_7c_narrowA",
            "A1_02_measurement", "C2_A1_08_overlap", "C2_A1_09_natfirst"]
CONFIG_LINE = re.compile(r'^do "00_config\.do" `vintage\'[ \t]*$', re.M)


def sub(text, old, new, expect=None, regex=False):
    """Replace and assert the count (expect=None: at least one)."""
    if regex:
        out, n = re.subn(old, new, text, flags=re.M)
    else:
        n = text.count(old)
        out = text.replace(old, new)
    if (expect is None and n < 1) or (expect is not None and n != expect):
        raise SystemExit(f"substitution count {n} (expected {expect or '>=1'}) for {old!r}")
    return out


def make_narrowA():
    src = (HERE / "A2_7b.do").read_text(encoding="utf-8")
    end = src.index("*******************************************************************************/") + len(
        "*******************************************************************************/")
    head = (
        "/*******************************************************************************\n"
        " C2_A2_7c_narrowA.do -- item A2.7c (Narrow-A benchmark). Generated by\n"
        " C2_A1_12_make_upair.py from A2_7b.do; the only changes are the outcome list (v_unesco_a = Narrow-A,\n"
        " UNESCO FCS2009-consistent basket A, 22 HS2007 codes, no 8523; PREP 01_prep.do section C) and the item\n"
        " and file tags (A2.7b -> A2.7c). Benchmarks, samples, fixed-point rule and stacked test (a2_stack,\n"
        " block-specific FE, cluster pair_id) exactly as A2_7b.do. Help: ppmlhdfe.sthlp, [R] test.\n"
        "*******************************************************************************/")
    t = src[end:]
    t = sub(t, "foreach Y in v_unesco_b v_nomedia {", "foreach Y in v_unesco_a {", 1)
    t = sub(t, 'local ytag = cond("`Y\'" == "v_unesco_b", "unesco_b", "nomedia")', 'local ytag "unesco_a"', 1)
    t = sub(t, 'local ylab = cond("`Y\'" == "v_unesco_b", "Narrow-B basket", "no recorded media")',
            'local ylab "Narrow-A basket"', 1)
    t = sub(t, "A2_7b", "A2_7c")
    t = sub(t, "A2.7b", "A2.7c")
    assert "v_unesco_b" not in t.split("foreach Y in", 1)[1].split("\n", 1)[0]
    return head + t


def make_up(stem, text):
    block = (
        '\n* UPAIR (C2_A1_12_make_upair.py): same estimates with clusters on the unordered pair; outputs go to the\n'
        '* sandbox ${OUTROOT}/${VINTAGE}_upair, inputs stay in the core folder.\n'
        'global OUT_CORE "${OUT}"\n'
        'global OUT "${OUTROOT}/${VINTAGE}_upair"\n'
        'global LOGS "${OUT}/logs"\n'
        'foreach d in "" "/logs" "/results" "/results/A1_parts" "/tables" "/pc" {\n'
        '    capture mkdir "${OUT}`d\'"\n'
        '}')
    t, n = CONFIG_LINE.subn(lambda m: m.group(0) + block, text, count=1)
    if n != 1:
        raise SystemExit(f"{stem}: config line not found")
    for f in ("A2_work.dta", "positive_controls.csv"):
        if f'"${{OUT}}/{f}"' in t:
            t = sub(t, f'"${{OUT}}/{f}"', f'"${{OUT_CORE}}/{f}"')
    n_vce = t.count("vce(cluster pair_id)")
    n_cl = t.count("cluster(pair_id)")
    n_a1 = len(re.findall(r"^\s*A1_stack,", t, flags=re.M))
    if n_vce + n_cl + n_a1 == 0:
        raise SystemExit(f"{stem}: no clustered estimate found")
    if n_vce:
        t = sub(t, "vce(cluster pair_id)", "vce(cluster unordered_pair_id)", n_vce)
    if n_cl:
        t = sub(t, "cluster(pair_id)", "cluster(unordered_pair_id)", n_cl)
    if n_a1:
        t = sub(t, r"^(\s*A1_stack,)", r"\1 cl(unordered_pair_id)", n_a1, regex=True)
    code = re.sub(r"/\*.*?\*/", "", t, flags=re.S)
    code = "\n".join(l.split("//")[0] for l in code.splitlines() if not l.lstrip().startswith("*"))
    left = re.findall(r"cluster\s*\(?\s*pair_id\b", code)
    if left:
        raise SystemExit(f"{stem}: directed clusters left: {left}")
    head = (f"* UP_{stem}.do -- GENERATED by C2_A1_12_make_upair.py from {stem}.do; do not edit.\n"
            f"* Changes: cluster variable pair_id -> unordered_pair_id ({n_vce} vce, {n_cl} stack, {n_a1} A1_stack);\n"
            f"* outputs in the sandbox folder ${{OUTROOT}}/${{VINTAGE}}_upair.\n")
    return head + t, (n_vce, n_cl, n_a1)


def build():
    files = {"C2_A2_7c_narrowA.do": make_narrowA()}
    counts = {}
    for stem in UP_STEMS:
        src = files["C2_A2_7c_narrowA.do"] if stem == "C2_A2_7c_narrowA" else (HERE / f"{stem}.do").read_text(encoding="utf-8")
        files[f"UP_{stem}.do"], counts[stem] = make_up(stem, src)
    return files, counts


def main():
    files, counts = build()
    check = "--check" in sys.argv[1:]
    bad = 0
    for name, text in files.items():
        p = HERE / name
        if check:
            if not p.exists() or p.read_text(encoding="utf-8") != text:
                print(f"CHECK FAIL {name}")
                bad += 1
        else:
            p.write_text(text, encoding="utf-8")
    for stem, (a, b, c) in counts.items():
        print(f"{stem}: vce {a}, stack {b}, A1_stack {c}")
    print(("CHECK " + ("FAIL" if bad else "PASS")) if check else f"wrote {len(files)} files")
    sys.exit(1 if bad else 0)


if __name__ == "__main__":
    main()
