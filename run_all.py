def hofstede_rebuild_needed():
    """True when the build's workbook is absent: its first sheet is then rebuilt from the official file."""
    return not (ROOT / PKG_XLS_REL).is_file()


def check_hofstede():
    """The Hofstede files are not redistributed (LICENSES_AND_SOURCES.md, section 6): stop with retrieval instructions.
    Only the public official file is required; without the build's workbook its sheet is rebuilt from the official file
    (tools/rebuild_hofstede_inputs.py; derived/hofstede/)."""
    import hashlib
    msgs = []
    for rel, sha, how in HOFSTEDE:
        p = ROOT / rel
        if not p.is_file() and rel == PKG_XLS_REL:
            continue
        if not p.is_file():
            msgs.append(f"MISSING {rel}\n  expected SHA-256 {sha}\n  {how}")
        elif hashlib.sha256(p.read_bytes()).hexdigest() != sha:
            msgs.append(f"CHANGED {rel}: SHA-256 differs from {sha}\n  {how}")
    if msgs:
        die("Hofstede input(s) missing or changed (not redistributable; obtain them as described):\n" + "\n".join(msgs))


