def stage_check(r, exe, args):
    check_hofstede()
    r.say(f"CHECK python {platform.python_version()} ({sys.executable}); platform {platform.platform()}; "
          f"machine {platform.machine()}; logical CPUs {os.cpu_count()}")
    if sys.version_info < (3, 10):
        die("Python 3.10 or newer is required (tested: 3.13.2).")
    missing = []
    for m in PY_MODULES:
        try:
            mod = __import__(m)
            r.say(f"CHECK module {m} {getattr(mod, '__version__', '?')}")
        except ImportError:
            missing.append(m)
    if missing:
        die("missing Python modules: " + ", ".join(missing) + ". Install with  python3 -m pip install -r requirements.txt")
    r.say(f"CHECK Stata {exe}")
    rc = run_stata(r, exe, ROOT / "install" / "check_stata_packages.do", [], RUN, "check_stata_packages", base_env(exe))
    if rc:
        die("Stata package check failed; see 05_output/_run/check_stata_packages.log "
            "(install with  python3 run_all.py --install-stata-packages).")
    if args.skip_raw_check:
        r.say("CHECK raw inputs skipped (--skip-raw-check)")
        return
    rc = r.run([sys.executable, str(ROOT / "tools" / "verify_raw_inputs.py"), "--root", str(ROOT), "--optional", PKG_XLS_REL],
               ROOT, base_env(exe))
    if rc:
        die("raw inputs incomplete or changed; see the list above and 01_raw/README.md (acquisition instructions).")


def run_stata(r, exe, dofile, dargs, cwd, tag, env):
    """Run one do-file in batch mode with cwd = the folder that receives its batch log; fail on an r(...) error."""
    cwd = Path(cwd)
    cwd.mkdir(parents=True, exist_ok=True)
    rc = r.run(stata_cmd(exe, dofile, dargs), cwd, env)
    if r.dry:
        return 0
    blog = cwd / (Path(dofile).stem + ".log")
    err = stata_failed(blog)
    if rc or err:
        r.say(f"STATA_ERROR {tag}: exit {rc} {err} (log {rel(blog)})")
        return 1
    return 0


def shim(exe):
    """POSIX: the chapter runners pass do-file paths as separate arguments; the shim quotes arguments with spaces (as
    Windows does) and adds -q (no licence banner in the logs). Windows: the real executable is used directly."""
    if os.name == "nt":
        return str(exe)
    s = ROOT / "02_code" / "99_rescue" / "bin" / "stata_quoted.sh"
    if not os.access(s, os.X_OK):
        s.chmod(s.stat().st_mode | 0o111)
    return str(s)


