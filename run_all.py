class Runner:
    def __init__(self, dry):
        self.dry = dry
        RUN.mkdir(parents=True, exist_ok=True)
        self.log = open(RUN / "run_all.log", "a", encoding="utf-8")
        self.times = RUN / "run_times.csv"
        if not self.times.exists():
            self.times.write_text("started,stage,step,vintage,seconds,status\n", encoding="utf-8")

    def say(self, msg):
        line = f"{dt.datetime.now():%Y-%m-%d %H:%M:%S} {msg}"
        print(line, flush=True)
        self.log.write(line + "\n")
        self.log.flush()

    def timed(self, stage, step, vintage, fn):
        t0 = time.time()
        start = f"{dt.datetime.now():%Y-%m-%d %H:%M:%S}"
        status = "FAIL"
        try:
            fn()
            status = "OK"
        finally:
            sec = round(time.time() - t0, 1)
            if not self.dry:
                with open(self.times, "a", encoding="utf-8", newline="") as fh:
                    csv.writer(fh).writerow([start, stage, step, vintage, sec, status])
            self.say(f"END {stage} {step} {vintage} {status} {sec}s")

    def run(self, cmd, cwd, env, logfile=None):
        shown = " ".join(cmd)
        self.say(f"RUN (cwd {rel(cwd)}): {shown}")
        if self.dry:
            return 0
        if logfile:
            with open(logfile, "w", encoding="utf-8") as fh:
                rc = subprocess.run(cmd, cwd=cwd, env=env, stdout=fh, stderr=subprocess.STDOUT).returncode
        else:
            rc = subprocess.run(cmd, cwd=cwd, env=env).returncode
        return rc


def rel(p):
    try:
        return str(Path(p).resolve().relative_to(ROOT)) or "."
    except ValueError:
        return str(p)


def die(msg):
    print("\nSTOP: " + msg, file=sys.stderr)
    sys.exit(2)


def find_stata(explicit):
    """--stata, STATA_EXE, PATH, then standard install locations; MP before SE before BE."""
    for cand in (explicit, os.environ.get("STATA_EXE", "").strip().strip('"')):
        if cand:
            p = Path(cand)
            if p.is_file():
                return p
            die(f"Stata executable not found: {p}")
    names_posix = ["stata-mp", "stata-se", "stata-be", "stata"]
    names_win = ["StataMP-64.exe", "StataSE-64.exe", "StataBE-64.exe", "Stata-64.exe", "StataMP.exe", "StataSE.exe", "Stata.exe"]
    for n in (names_win if os.name == "nt" else names_posix):
        w = shutil.which(n)
        if w:
            return Path(w)
    cands = []
    if sys.platform == "darwin":
        for app in ("StataNow", "Stata"):
            for ed, exe in (("StataMP", "stata-mp"), ("StataSE", "stata-se"), ("StataBE", "stata-be")):
                cands.append(Path("/Applications") / app / f"{ed}.app" / "Contents" / "MacOS" / exe)
    elif os.name == "nt":
        for key in ("ProgramFiles", "ProgramW6432", "ProgramFiles(x86)"):
            base = os.environ.get(key)
            if not base:
                continue
            for folder in ("StataNow19", "Stata19", "StataNow18", "Stata18"):
                for n in names_win:
                    cands.append(Path(base) / folder / n)
    else:
        for folder in ("/usr/local/stata19", "/usr/local/stata18", "/usr/local/stata", "/opt/stata19", "/opt/stata18", "/opt/stata"):
            for n in names_posix:
                cands.append(Path(folder) / n)
    for c in cands:
        if c.is_file():
            return c
    die("Stata not found. Set STATA_EXE to the Stata executable or pass --stata PATH (README.md, Software).")


def qarg(a):
    """Stata for macOS/Unix joins its arguments with spaces, so an argument with a space must carry its own quotes
    (on Windows subprocess quotes every argument with a space)."""
    a = str(a)
    if os.name == "nt":
        return a
    if '"' in a:
        die(f"argument contains a double quote, cannot be passed to Stata: {a}")
    return f'"{a}"' if (a == "" or re.search(r"\s", a)) else a


def stata_cmd(exe, dofile, args):
    if os.name == "nt":
        return [str(exe), "/e", "/q", "do", str(dofile), *map(str, args)]
    return [str(exe), "-b", "-q", "do", qarg(dofile), *map(qarg, args)]


def stata_failed(batch_log):
    if not batch_log.is_file():
        return "no batch log"
    tail = batch_log.read_text(encoding="utf-8", errors="replace").splitlines()[-40:]
    errs = [l for l in tail if re.match(r"^r\(\d+\);\s*$", l)]
    return errs[-1] if errs else ""


def no_space_tmp():
    t = os.environ.get("PKG_STATATMP") or tempfile.gettempdir()
    if re.search(r"\s", t):
        die(f"The temporary folder for Stata contains a space ({t}); did_multiplegt_dyn needs one without spaces "
            "(README.md, known limitations). Set PKG_STATATMP to an existing folder without spaces.")
    return t


def base_env(exe):
    env = os.environ.copy()
    for k in ("PYTHONPATH", "PYTHONHOME", "PYTHONOPTIMIZE", "PYTHONSTARTUP", "REPLICATION_ROOT"):
        env.pop(k, None)
    ado = [ROOT / "02_code" / "99_rescue" / "stata", ROOT / "02_code" / "99_rescue" / "ado"]
    # package ados (correction switch rescue_on, nflow 1.0.1) right after BASE; then Stata's default search path
    env["S_ADO"] = "BASE;" + ";".join(f'"{p.as_posix()}"' for p in ado) + ";SITE;.;PERSONAL;PLUS;OLDPLACE"
    env["PKG_ROOT"] = ROOT.as_posix()
    env["PKG_PYTHON"] = sys.executable
    env["PYTHONDONTWRITEBYTECODE"] = "1"
    env["MPLCONFIGDIR"] = str(RUN / "mplconfig")
    env["PYTHONUTF8"] = "1"
    return env


