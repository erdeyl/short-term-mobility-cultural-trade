def analysis_step(r, exe, env, v, step):
    out = OUTROOT / v
    for d in ("logs", "results/A1_parts", "tables", "pc"):
        if not r.dry:
            (out / d).mkdir(parents=True, exist_ok=True)
    if step == "FIG_03_cd_slopes" and v not in ("corrected2", "corrected2x"):
        return
    if step in FINAL_ONLY and v != "corrected2x":
        return
    if step == "MIRROR30":
        if v != "corrected2x":
            return
        logf = out / "logs" / "C2_01_mirror_ex4907_corrected2x.log"
        rc = r.run([sys.executable, str(CODE / "C2_01_mirror_ex4907.py")], ROOT, env, logfile=None if r.dry else logf)
        if rc:
            die(f"C2_01_mirror_ex4907.py failed; see {rel(logf)}")
        return
    parts = step.split(":")
    stem, extra = parts[0], parts[1:]
    tag = "_".join(extra)
    name = f"{stem}_{v}" + (f"_{tag}" if tag else "") + "_batch"
    wrapper = out / "logs" / f"{name}.do"
    if not r.dry:
        wrapper.write_text(
            "* generated by run_all.py: the package root is the first argument\n"
            "args root\n"
            'global PKGROOT `"`root\'"\'\n'
            'cd `"`root\'/02_code/10_analysis"\'\n'
            f'do "{stem}.do" {v} {" ".join(extra)}\n', encoding="utf-8")
    rc = run_stata(r, exe, wrapper, [ROOT.as_posix()], out / "logs", name, env)
    if rc:
        die(f"{stem} ({v}) failed; see 05_output/10_analysis/{v}/logs/{name}.log")


def stage_analysis(r, exe, args, vintages):
    check_hofstede()
    env = base_env(exe)
    env["STATATMP"] = no_space_tmp()
    hof = OUTROOT / "A2_hofstede"
    pkg_xls = sorted((ROOT / "01_raw" / "05_Mobility").glob("6-dimensions-for-website-2015-08-16*.xls"))
    pre = [
        ("A1_names", [sys.executable, str(CODE / "A1_names.py"), str(ROOT / "01_raw/02_UN_Comtrade/reference/partnerAreas.json"),
                      str(OUTROOT / "A1_un_names.csv")]),
        ("A2_00a_hofstede_sheets", [sys.executable, str(CODE / "A2_00a_hofstede_sheets.py"),
                                    str(ROOT / "01_raw/08_Hofstede_official/6-dimensions-for-website-2015-08-16.xls"),
                                    str(pkg_xls[0]) if pkg_xls else "-", str(hof / "sheets")]),
        ("A2_00_hofstede", [sys.executable, str(CODE / "A2_00_hofstede.py"), str(hof / "sheets"), str(hof)]),
    ]
    if not pkg_xls:  # the build's workbook is absent: its sheet export is rebuilt from the official file
        pre.insert(2, ("rebuild_hofstede_inputs", [sys.executable, str(ROOT / "tools" / "rebuild_hofstede_inputs.py"),
                                                   str(ROOT / HOFSTEDE[0][0]), str(hof / "sheets")]))
    if not r.dry:
        OUTROOT.mkdir(parents=True, exist_ok=True)
    for name, cmd in pre:
        r.timed("analysis", name, "-", lambda cmd=cmd, name=name: r.run(cmd, ROOT, env) == 0 or die(f"{name} failed"))
    for v in vintages:
        steps = SUBMITTED if v == "submitted" else FULL
        for s in steps:
            r.timed("analysis", s, v, lambda s=s, v=v: analysis_step(r, exe, env, v, s))
    if args.reconciliation:
        extra = []
        if "submitted" in vintages:
            extra.append(("corrected", "A1_06_crossvintage"))
        if "corrected2" in vintages:
            extra.append(("corrected2", "C2_00_controls:corrected"))
            extra.append(("corrected2x", "C2_00_controls:corrected2"))
        for v, s in extra:
            r.timed("analysis", s, v, lambda s=s, v=v: analysis_step(r, exe, env, v, s))


